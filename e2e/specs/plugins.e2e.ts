import { $, browser, expect } from '@wdio/globals';
import { dirname, join } from 'node:path';
import { snapshotVault, diffSnapshots } from '../../scripts/vault-snapshot.mjs';
import { vaultCopy } from '../paths';
import { openFolders, openNote, prepareWindow, screenshot, scrollIntoView, showTab, selectOption } from '../support';
const root = join(dirname(vaultCopy()), 'plugins-vault');
const DAY = 'Journal/24.11.2026.md';
async function save() { await scrollIntoView('[data-testid="settings-save"]'); await $('[data-testid="settings-save"]').click(); await $('[data-testid="settings"] .save-state').waitForDisplayed(); }
async function toggle(name: string) { await $(`[aria-label="Enable ${name}"]`).click(); }
describe('a Markdown core with optional workflows', () => {
  before(prepareWindow);
  it('starts without workflows and enables only selected plugins without changing notes', async () => {
    const before = snapshotVault(root);
    await expect($('[data-testid="markdown-home"]')).toBeDisplayed();
    for (const id of ['calendar', 'open-library', 'open-habits', 'open-statistics', 'open-graph']) await expect($(`[data-testid="${id}"]`)).not.toBeExisting();
    await screenshot('200-markdown-core');
    await openFolders('Journal'); await openNote(DAY);
    await expect($('[data-testid="periodic"]')).not.toBeExisting();
    await $('[data-testid="open-settings"]').click();
    await screenshot('201-plugin-catalog');
    for (const name of ['Homepage', 'Periodic notes', 'Check-ins', 'Habits', 'CBT', 'Statistics']) await toggle(name);
    await $('[aria-label="Configure Check-ins"]').click();
    for (const name of ['Energy', 'Focus', 'Social']) await $(`.plugin-checks input[aria-label="${name}"]`).click();
    await scrollIntoView('[data-plugin="checkins"]');
    await screenshot('202-check-in-preferences');
    await save();
    expect(diffSnapshots(before, snapshotVault(root))).toEqual([]);
    await openFolders('Journal'); await openNote(DAY); await showTab('Overview');
    await expect($('[data-testid="check-in"] [data-metric="mood"]')).toBeDisplayed();
    await expect($('[data-testid="check-in"] [data-metric="sleep"]')).toBeDisplayed();
    for (const key of ['energy', 'focus', 'soc']) await expect($(`[data-testid="check-in"] [data-metric="${key}"]`)).not.toBeExisting();
    await expect($('[data-testid="tab"][data-tab="CBT"]')).toBeDisplayed();
    await expect($('[data-testid="tab"][data-tab="Stream"]')).not.toBeExisting();
    await screenshot('203-custom-daily-note');
  });
  it('hides disabled CBT, habits and check-ins, preserving historical averages and all Markdown', async () => {
    const before = snapshotVault(root);
    await showTab('CBT');
    await $('[data-testid="open-settings"]').click();
    for (const name of ['CBT', 'Habits', 'Check-ins']) await toggle(name);
    await save();
    await openFolders('Journal'); await openNote(DAY);
    await expect($('[data-testid="tab"][data-tab="Overview"]')).toHaveAttribute('aria-selected', 'true');
    for (const name of ['CBT', 'Habits']) await expect($(`[data-testid="tab"][data-tab="${name}"]`)).not.toBeExisting();
    await expect($('[data-testid="check-in"]')).not.toBeExisting();
    await expect($('[data-testid="open-habits"]')).not.toBeExisting();
    await screenshot('204-daily-without-optional-blocks');
    await $('[data-testid="sidebar-vault"]').click();
    await $('[data-testid="open-summaries"]').click();
    const november = $('[data-month="2026-11"]');
    await expect(november.$('[data-metric="focus"]')).toHaveText('Focus3.67');
    await expect(november.$('[data-metric="energy"]')).not.toBeExisting();
    await expect($('[data-month="2026-12"] [data-metric="focus"]')).not.toBeExisting();
    await scrollIntoView('[data-month="2026-11"]');
    await screenshot('205-sparse-month-statistics');
    expect(diffSnapshots(before, snapshotVault(root))).toEqual([]);
    await browser.refresh(); await prepareWindow();
    await $('[data-testid="open-settings"]').click();
    await expect($('[aria-label="Enable CBT"]')).not.toBeSelected();
    await toggle('Periodic notes'); await save();
    await expect($('[data-testid="calendar"]')).not.toBeExisting();
    await openFolders('Journal'); await openNote(DAY);
    await expect($('[data-testid="periodic"]')).not.toBeExisting();
    await screenshot('206-periodic-as-markdown');
    expect(diffSnapshots(before, snapshotVault(root))).toEqual([]);
  });
  it('saves per-plugin display choices, applies them to screens and retains them after reload', async () => {
    const before = snapshotVault(root);
    await $('[data-testid="open-settings"]').click();
    await toggle('Habits');
    await $('[aria-label="Configure Habits"]').click();
    await selectOption('[aria-label="Habits layout"]', 'compact');
    await selectOption('[aria-label="Habits default view"]', 'History');
    await $('label=Today’s progress').$('input').click();
    await screenshot('225-plugin-habits-display');
    await $('[aria-label="Configure Statistics"]').click();
    await selectOption('[aria-label="Statistics default view"]', 'Yearly');
    await $('label=Focus activity map').$('input').click();
    await $('[aria-label="Configure Periodic notes"]').click();
    await selectOption('[aria-label="Periodic notes default view"]', 'Tasks');
    await save();
    await $('[data-testid="open-habits"]').click();
    await expect($('[data-plugin-display="habits"]')).toHaveAttribute('data-density', 'compact');
    await expect($('[aria-label="Habit collection"]').$('button*=History')).toHaveAttribute('aria-pressed', 'true');
    await expect($('.habits-today')).not.toBeExisting();
    await screenshot('226-plugin-habits-compact');
    await $('[data-testid="open-statistics"]').click();
    await expect($('[aria-label="Focus period"]').$('button=Yearly')).toHaveAttribute('class', expect.stringContaining('is-on'));
    await openFolders('Journal'); await openNote(DAY);
    await expect($('[data-testid="tab"][data-tab="Tasks"]')).toHaveAttribute('aria-selected', 'true');
    await browser.refresh(); await prepareWindow();
    await $('[data-testid="open-settings"]').click();
    await $('[aria-label="Configure Habits"]').click();
    await expect($('[aria-label="Habits layout"]')).toHaveValue('compact');
    await expect($('[aria-label="Habits default view"]')).toHaveValue('History');
    expect(diffSnapshots(before, snapshotVault(root))).toEqual([]);
  });
});
