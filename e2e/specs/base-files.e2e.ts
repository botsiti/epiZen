import { $, $$, browser, expect } from '@wdio/globals';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { diffSnapshots, snapshotVault } from '../../scripts/vault-snapshot.mjs';
import { vaultCopy } from '../paths';
import { MUSIC_FILE, MUSIC_FILE_SOURCE } from '../bases-fixture';
import { openFolders, openNote, prepareWindow, screenshot, scrollIntoView } from '../support';
const root = join(dirname(vaultCopy()), 'base-files-vault');
async function select(selector: string, value: string) {
  await browser.execute((css, value) => { const element = document.querySelector<HTMLSelectElement>(css); if (!element) throw new Error(`Missing ${css}`); element.value = value; element.dispatchEvent(new Event('change', { bubbles: true })); }, selector, value);
}
async function base() {
  await openFolders('Rating', 'Rating/music');
  await $(`[data-testid="tree-note"][data-path="${MUSIC_FILE}"]`).click();
  await $('[data-testid="base-document"]').waitForDisplayed();
  await $('[data-testid="base-block"] .base-count').waitForDisplayed();
}
describe('Obsidian .base migration and editable views', () => {
  before(prepareWindow);
  it('opens table, cards, list and named embeds with formulas without rewriting anything', async () => {
    const before = snapshotVault(root); await base();
    await expect($('.base-count')).toHaveText('20 notes');
    await expect($('.base-scroll tbody tr')).toHaveText(expect.stringContaining('Seven Bells for Nobody'));
    await expect($('.base-scroll tbody tr')).toHaveText(expect.stringContaining('4.5'));
    await expect($('.base-value-error')).not.toBeExisting();
    await screenshot('190-base-file-table');
    await select('[aria-label="Table view"]', '1');
    await expect($$('.base-card')).toBeElementsArrayOfSize(20);
    await $('.base-card [data-testid="vault-image"]').waitForDisplayed();
    await screenshot('191-base-file-cards');
    await select('[aria-label="Table view"]', '2');
    await expect($$('.base-list > li')).toBeElementsArrayOfSize(20);
    await screenshot('192-base-file-list');
    await openNote('Base embeds.md');
    await expect($('[aria-label="Table view"]')).toHaveValue('1');
    await expect($('.base-card')).toBeDisplayed();
    expect(diffSnapshots(before, snapshotVault(root))).toEqual([]);
  });
  it('saves visible properties, nested filters and a new view while preserving other YAML', async () => {
    const before = snapshotVault(root); await base();
    await $('button=Properties').click();
    await screenshot('193-base-properties');
    await browser.execute(() => { const label = [...document.querySelectorAll('.base-property-option label')].find((item) => item.textContent?.includes('Artist')); label?.querySelector<HTMLInputElement>('input')?.click(); });
    await $('.base-popover').$('button=Apply').click();
    await browser.waitUntil(() => !readFileSync(join(root, MUSIC_FILE), 'utf8').includes('order: [file.name, Artist, rating, formula.stars, listened]'));
    await $('button=Filter').click();
    await $('button=+ Add filter group').click();
    await $('.base-filter-group .base-filter-group').$('button=+ Add filter').click();
    await select('.base-filter-group .base-filter-group [aria-label="Filter property"]', 'note.rating');
    await select('.base-filter-group .base-filter-group [aria-label="Filter comparison"]', '>=');
    await select('.base-filter-group .base-filter-group [aria-label="Filter value type"]', 'number');
    await $('.base-filter-group .base-filter-group [aria-label="Filter value"]').setValue('80');
    await screenshot('194-base-filters');
    await $('.base-popover').$('button=Apply').click();
    await expect($('.base-count')).toHaveText('8 notes');
    await $('button=Views').click();
    await $('button=+ Add view').click();
    await $('[aria-label="New view name"]').setValue('Favorites gallery');
    await select('[aria-label="New view layout"]', 'cards');
    await $('button=Create view').click();
    await expect($('[aria-label="Table view"]')).toHaveValue('3');
    const source = readFileSync(join(root, MUSIC_FILE), 'utf8');
    expect(source).toContain('customSetting: retain-me');
    expect(source).toContain('# An existing Obsidian Base');
    expect(source).toContain('name: Listening list');
    expect(diffSnapshots(before, snapshotVault(root))).toEqual([`changed: ${MUSIC_FILE}`]);
    await browser.refresh(); await prepareWindow(); await base();
    await expect($('.base-count')).toHaveText('8 notes');
    await expect($$('[aria-label="Table view"] option')).toBeElementsArrayOfSize(4);
  });
  it('edits a property in its Markdown note and imports a base byte-for-byte', async () => {
    await base(); const before = snapshotVault(root);
    const path = 'Rating/music/Seven Bells for Nobody.md', original = readFileSync(join(root, path), 'utf8');
    await $('[aria-label="Edit rating in Seven Bells for Nobody"]').click();
    await $('.base-cell-editor textarea').setValue('91');
    await $('.base-cell-editor').$('button=Save').click();
    await browser.waitUntil(() => readFileSync(join(root, path), 'utf8').includes('rating: 91'));
    expect(readFileSync(join(root, path), 'utf8')).toBe(original.replace('rating: 90', 'rating: 91'));
    expect(diffSnapshots(before, snapshotVault(root))).toEqual([`changed: ${path}`]);
    await $('[data-testid="new-base-button"]').click();
    await browser.execute((source) => { const input = document.querySelector<HTMLInputElement>('[data-testid="import-base-file"]')!; const files = new DataTransfer(); files.items.add(new File([source], 'Imported collection.base', { type: 'text/plain' })); input.files = files.files; input.dispatchEvent(new Event('change', { bubbles: true })); }, MUSIC_FILE_SOURCE);
    await expect($('[data-testid="new-base-name"]')).toHaveValue('Imported collection');
    await screenshot('195-base-import');
    await $('[data-testid="create-base"]').click();
    await $('[data-testid="base-document"][data-path="Rating/music/Imported collection.base"]').waitForDisplayed();
    expect(readFileSync(join(root, 'Rating/music/Imported collection.base'), 'utf8')).toBe(MUSIC_FILE_SOURCE);
    await browser.setWindowSize(880, 760);
    await scrollIntoView('[data-testid="base-block"]');
    await screenshot('196-base-file-narrow');
    await $('button=Filter').click();
    await screenshot('197-base-filters-narrow');
    const panel = await $('.base-popover').getSize();
    expect(panel.width).toBeLessThan(880);
    const contained = await browser.execute(() => { const panel = document.querySelector('.base-popover')!.getBoundingClientRect(), pane = document.querySelector('.main')!.getBoundingClientRect(); return panel.left >= pane.left && panel.right <= pane.right && panel.top >= pane.top && panel.bottom <= pane.bottom; });
    expect(contained).toBe(true);
    await $('[aria-label="Close settings"]').click();
    expect(await browser.execute(() => document.querySelector('.main')!.scrollWidth > document.querySelector('.main')!.clientWidth)).toBe(false);
  });
});
